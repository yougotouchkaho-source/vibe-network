Vibe Network

Описание проекта

Vibe Network — публичный блокчейн с собственной нативной монетой VIBE.

Основные параметры

- Название сети: Vibe Network
- Название монеты: Vibe Coin
- Символ: VIBE
- Начальная эмиссия: 1 000 000 000 VIBE
- Разрядность: 18 знаков после запятой
- Консенсус: Proof of Stake (доказательство доли)
- Совместимость: Ethereum Virtual Machine (EVM)
- Адреса кошельков: формат 0x
- Планируемое время блока: 2 секунды
- Максимальное количество активных валидаторов: 100

Экосистема

- Vibe Network — блокчейн
- Vibe Coin — нативная монета
- Vibe DEX — децентрализованная биржа
- Vibe Explorer — обозреватель блоков
- Vibe Wallet — кошелёк
- Vibe Staking — делегирование и стейкинг

Языки сайта

- Русский
- Английский

Дизайн

Премиальный стиль: чёрный, фиолетовый и серебряный.

Статус

Проект находится на стадии разработки. Основная сеть, монета и биржа ещё не запущены.
